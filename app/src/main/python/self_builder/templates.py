"""
Self-Builder - code templates and test generation
=================================================
`generate_module()` turns a validated spec into the source text of ONE Python
module; `generate_test_suite()` builds the JSON test suite that is run
against it. This is template instantiation, not free-form code generation:
every generated module has a fixed shape (metadata constants, one core
function, one `run(inputs)` entry point), contains no imports, loops,
attribute access or string processing, and only calls the sandbox helpers
(helpers.py) - which the AST validator (validator.py) enforces afterwards.

The expected values in a generated test suite come from an independent
reference path (exact rational arithmetic for unit conversions, the tree
evaluator in expr.py for formulas, the reviewed text operations for text
tools), so running the suite is a real differential test of the generated
module, not a tautology.
"""

import math
from fractions import Fraction

from . import expr as expr_mod
from . import mathcore, policy, spec as spec_mod, textops, units
from .errors import SpecError

TEMPLATE_SCHEMA = 1

_HEADER = (
    "# Generated by the Self-Builder (template schema {schema}) - kind: {kind}.\n"
    "# Do not edit: the registry records this file's SHA-256 and refuses a modified file.\n"
)


def _num(value):
    return repr(float(value))


def generate_module(spec, version):
    """Source text of the module for `spec` at `version`."""
    spec_mod.validate_spec(spec)
    kind = spec["kind"]
    cid = spec["capability_id"]
    lines = [_HEADER.format(schema=TEMPLATE_SCHEMA, kind=kind).rstrip("\n"),
             f"CAPABILITY_ID = {cid!r}",
             f"CAPABILITY_VERSION = {int(version)}",
             f"CAPABILITY_KIND = {kind!r}"]
    if kind == policy.ARCHETYPE_UNIT_CONVERSION:
        lines += [f"SCALE = {_num(spec['scale'])}",
                  f"SHIFT = {_num(spec['shift'])}",
                  "",
                  "",
                  "def convert(x_value):",
                  "    return _sb_finite(((x_value * SCALE) + SHIFT))",
                  "",
                  "",
                  "def run(inputs):",
                  "    return {\"value\": convert(_sb_number_input(inputs, \"value\"))}"]
    elif kind == policy.ARCHETYPE_FORMULA:
        names = [v["name"] for v in spec["variables"]]
        params = ", ".join(expr_mod.PARAM_PREFIX + n for n in names)
        call_args = ", ".join(f"_sb_number_input(inputs, {n!r})" for n in names)
        names_tuple = "(" + ", ".join(repr(n) for n in names) + ("," if len(names) == 1 else "") + ")"
        body = expr_mod.to_source(spec["tree"])
        lines += [f"VARIABLES = {names_tuple}",
                  "",
                  "",
                  f"def compute({params}):",
                  f"    return _sb_finite({body})",
                  "",
                  "",
                  "def run(inputs):",
                  f"    return {{\"value\": compute({call_args})}}"]
    else:
        ops = list(spec["ops"])
        ops_tuple = "(" + ", ".join(repr(o) for o in ops) + ("," if len(ops) == 1 else "") + ")"
        value = "x_text"
        for op in ops:
            value = f"{textops.HELPER_PREFIX}{op}({value})"
        lines += [f"OPS = {ops_tuple}",
                  "",
                  "",
                  "def process(x_text):",
                  f"    return {value}",
                  "",
                  "",
                  "def run(inputs):",
                  "    return {\"value\": process(_sb_text_input(inputs, \"text\"))}"]
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------------- tests --

_CONVERSION_VALUES = [0.0, 1.0, -1.0, 2.5, 10.0, 100.0, 1234.5678, 1e6, -273.15]
_FORMULA_GRID = [1.0, 2.0, 3.5, 0.5, 10.0, -1.0, 0.0, 100.0, 7.25, -2.5]
_TEXT_SAMPLES = ["", "سلام دنیا", "  می خواهم   بروم  ", "Hello World", "۱۲۳ abc ٤٥٦", "كتاب ي", "a b  c", "x" * 40]


def _conversion_reference(spec, value):
    """Exact-rational reference of value * scale + shift for the spec's own
    parameters (independent of the float arithmetic in the generated code)."""
    ref = Fraction(repr(float(value))) * Fraction(repr(float(spec["scale"]))) + Fraction(repr(float(spec["shift"])))
    try:
        return float(ref)
    except OverflowError:
        return math.inf  # mathcore.finite() turns this into the "overflow" failure


def reference_result(spec, inputs):
    """Reference answer for `inputs`: {"value": x} or {"error": code}."""
    kind = spec["kind"]
    try:
        if kind == policy.ARCHETYPE_UNIT_CONVERSION:
            return {"value": mathcore.finite(_conversion_reference(spec, inputs["value"]))}
        if kind == policy.ARCHETYPE_FORMULA:
            env = {k: float(v) for k, v in inputs.items()}
            return {"value": expr_mod.evaluate_final(spec["tree"], env)}
        return {"value": textops.apply_ops(spec["ops"], inputs["text"])}
    except mathcore.MathFailure as e:
        return {"error": e.code}


def _expect_from_reference(spec, inputs):
    ref = reference_result(spec, inputs)
    if "error" in ref:
        return {"error": ref["error"]}
    value = ref["value"]
    if isinstance(value, str):
        return {"value": value}
    return {"value": value, "rel_tol": 1e-12, "abs_tol": 1e-9}


def generate_test_suite(spec, version):
    """JSON-serialisable test suite for `spec` at `version`."""
    kind = spec["kind"]
    cases = []

    def add(name, inputs, expect):
        if len(cases) < policy.MAX_TEST_CASES:
            cases.append({"name": name, "inputs": inputs, "expect": expect})

    if kind == policy.ARCHETYPE_UNIT_CONVERSION:
        for i, v in enumerate(_CONVERSION_VALUES):
            add(f"auto_{i}", {"value": v}, _expect_from_reference(spec, {"value": v}))
        add("bad_missing", {}, {"error": "bad_input"})
        add("bad_text", {"value": "abc"}, {"error": "bad_input"})
        add("bad_bool", {"value": True}, {"error": "bad_input"})
        add("huge_value", {"value": 1e308}, _expect_from_reference(spec, {"value": 1e308}))
    elif kind == policy.ARCHETYPE_FORMULA:
        names = [v["name"] for v in spec["variables"]]
        seen = set()
        grid = _FORMULA_GRID
        for k in range(14):
            env = {n: grid[(k * 3 + j * 5 + (k // len(grid))) % len(grid)] for j, n in enumerate(names)}
            sig = tuple(sorted(env.items()))
            if sig in seen:
                continue
            seen.add(sig)
            add(f"auto_{len(seen) - 1}", env, _expect_from_reference(spec, env))
        for extra_name, value in (("all_zero", 0.0), ("all_one", 1.0)):
            env = {n: value for n in names}
            if tuple(sorted(env.items())) not in seen:
                add(extra_name, env, _expect_from_reference(spec, env))
        add("bad_missing", {}, {"error": "bad_input"})
        add("bad_text", {names[0]: "abc"}, {"error": "bad_input"})
        add("bad_bool", {n: True for n in names}, {"error": "bad_input"})
    else:
        for i, text in enumerate(_TEXT_SAMPLES):
            add(f"auto_{i}", {"text": text}, _expect_from_reference(spec, {"text": text}))
        add("bad_missing", {}, {"error": "bad_input"})
        add("bad_number", {"text": 5}, {"error": "bad_input"})
        add("bad_too_long", {"text": "x" * (policy.MAX_INVOKE_TEXT_CHARS + 1)}, {"error": "bad_input"})

    for i, ex in enumerate(spec.get("examples") or []):
        expected = ex["expected"]
        if isinstance(expected, str):
            expect = {"value": expected}
        else:
            tol = ex.get("tolerance")
            expect = {"value": float(expected), "abs_tol": float(tol) if tol is not None else 1e-9,
                      "rel_tol": 0.0 if tol is not None else 1e-9}
        # user examples are not subject to the case cap
        cases.append({"name": f"example_{i}", "inputs": dict(ex["inputs"]), "expect": expect, "source": "user"})

    return {
        "schema": TEMPLATE_SCHEMA,
        "capability_id": spec["capability_id"],
        "version": int(version),
        "kind": kind,
        "cases": cases,
    }


def check_expectation(expect, actual_value=None, actual_error=None):
    """(passed, reason) for one case outcome."""
    if "error" in expect:
        if actual_error == expect["error"]:
            return True, "expected error raised"
        return False, f"expected error {expect['error']!r}, got " + (
            f"error {actual_error!r}" if actual_error else f"value {actual_value!r}")
    if actual_error is not None:
        return False, f"unexpected error {actual_error!r}"
    want = expect["value"]
    if isinstance(want, str):
        return (actual_value == want, "text equal" if actual_value == want else
                f"expected {want!r}, got {actual_value!r}")
    if isinstance(actual_value, bool) or not isinstance(actual_value, (int, float)):
        return False, f"expected a number, got {type(actual_value).__name__}"
    tol = max(float(expect.get("abs_tol", 0.0)), float(expect.get("rel_tol", 0.0)) * abs(want))
    ok = math.isfinite(actual_value) and abs(actual_value - want) <= tol
    return ok, "within tolerance" if ok else f"expected {want!r}, got {actual_value!r} (tolerance {tol!r})"
