# ------------------------------------------------------------------ «از مغزت بخواه برایم X بسازد» (the own-brain teacher)
_PACK_KIND_FA = {"code": "یک بستهٔ کد (قابلیت تازه برای خود همین برنامه)", "lang": "یک بستهٔ زبان (داده‌های پرسش و پاسخ فارسی)"}
_NEEDS_SETUP = frozenset({"off", "no_provider", "no_consent", "no_key"})
MAX_SHOWN_CHARS = 800


def _clip(text, limit):
    text = " ".join(str(text or "").split())
    return text if len(text) <= limit else text[:limit - 1] + "…"


