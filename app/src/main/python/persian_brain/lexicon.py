"""
Persian conversation brain - closed word lists
==============================================
The small, fixed vocabularies the intent classifier compares tokens against.
They are deliberately small and structural (greeting words, yes/no words,
feedback words, question words, command nouns); there is no table of
sentence -> answer anywhere. Every phrase is stored as the token tuple that
`normalization.tokens()` produces, so spelling variants that normalization
already merges (ي/ی, ك/ک, ZWNJ/space, digits) need no duplicate entries.

Where colloquial spellings differ in more than normalization can merge
("میخوام" / "می‌خواهم" / "میخواهم") both forms are listed.
"""

from self_builder import fa_text


def phrase(text):
    return tuple(fa_text.words(text))


def phrases(*texts):
    return frozenset(phrase(t) for t in texts)


# plural / possessive suffixes that ZWNJ-splitting turns into separate tokens
# ("قابلیت‌هایت" -> "قابلیت" + "هایت"): never a word of their own in a bag of words
_SUFFIX_TOKENS = frozenset({"ها", "های", "هایی", "هایت", "هات", "هایم", "هام", "هایش", "هاش", "هاشون", "هایتان"})


def word_set(*texts):
    return frozenset(w for t in texts for w in fa_text.words(t) if w not in _SUFFIX_TOKENS)


def contains(tokens, ph):
    """Is the token tuple `ph` a contiguous part of `tokens`?"""
    n = len(ph)
    if n == 0 or n > len(tokens):
        return False
    return any(tuple(tokens[i:i + n]) == ph for i in range(len(tokens) - n + 1))


def starts_with(tokens, ph):
    return len(ph) <= len(tokens) and tuple(tokens[:len(ph)]) == ph


def any_phrase(tokens, group):
    return any(contains(tokens, ph) for ph in group)


