def blocked(code, label_fa, secret):
    if secret:
        return ("این پیام شبیه «%s» بود، پس به مغز ابری نفرستادمش و فقط روی گوشی ماند. %s اگر سؤالی داری، همان را بدون آن عدد یا رمز بنویس." %
                (label_fa, _BLOCK_HINT.get(code, "")))
    return ("این پیام «%s» داشت، پس به مغز ابری نفرستادمش. اگر می‌خواهی چنین پیام‌هایی هم برود بگو «اطلاعات شخصی را هم برای مغز ابری بفرست»." % label_fa)


